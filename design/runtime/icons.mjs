/** Trusted registry only. A label makes the SVG meaningful; otherwise it is decorative.
 * Native controls retain their browser markers. Icons never determine hit-area size. */
export function iconModel(name, {size='medium', label, decorative=label===undefined} = {}) {
 if (!Object.hasOwn(icons,name)) throw new Error('Unknown shared Tabler icon: '+String(name));
 if (!Object.hasOwn(sizes,size)) throw new Error('Unknown shared icon size: '+String(size));
 if (!decorative && !String(label??'').trim()) throw new Error('Meaningful icon requires an accessible label.');
 const entry=icons[name];
 const attrs={xmlns:'http://www.w3.org/2000/svg',class:'ds-icon','data-icon':name,'data-size':size,width:String(sizes[size]),height:String(sizes[size]),viewBox:'0 0 24 24',fill:entry.filled?'currentColor':'none',focusable:'false',...(decorative?{'aria-hidden':'true'}:{role:'img','aria-label':String(label)})};
 if (!entry.filled)Object.assign(attrs,{stroke:'currentColor','stroke-width':'2','stroke-linecap':'round','stroke-linejoin':'round'});
 return {tag:'svg',attrs,children:entry.children.map(child=>({tag:child.tag,attrs:{...child.attrs},children:[]}))};
}
export function renderIcon(name, options={}) {
 const serialize=node=>'<'+node.tag+Object.entries(node.attrs).map(([key,value])=>' '+key+'="'+escape(value)+'"').join('')+'>'+(node.children??[]).map(serialize).join('')+'</'+node.tag+'>';
 return serialize(iconModel(name,options));
}
export function createIcon(name, options={}, {document=globalThis.document}={}) {
 if (!document?.createElement)throw new Error('createIcon requires a DOM document.');
 const create=node=>{
  const element=document.createElementNS?document.createElementNS('http://www.w3.org/2000/svg',node.tag):document.createElement(node.tag);
  for (const [key,value] of Object.entries(node.attrs))element.setAttribute(key,value);
  for (const child of node.children??[])element.appendChild(create(child));
  return element;
 };
 return create(iconModel(name,options));
}
export function generateIconCSS(scope='.ds-scope') {
 if (!/^[.#][a-zA-Z_][a-zA-Z0-9_-]*$/.test(scope))throw new Error('CSS scope must be a single class or ID selector.');
 const selector=`:where(${scope}) .ds-icon, :where(${scope}).ds-icon`;
 return [
  `${selector} { display: inline-block; flex: 0 0 auto; vertical-align: middle; pointer-events: none; }`,
  ...Object.entries(sizes).map(([size,value])=>`:where(${scope}) .ds-icon[data-size="${size}"], :where(${scope}).ds-icon[data-size="${size}"] { inline-size: var(--ds-size-icon-${size}, ${value}px); block-size: var(--ds-size-icon-${size}, ${value}px); }`),
 ].join('\n');
}
